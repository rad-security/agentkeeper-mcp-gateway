#!/usr/bin/env bash
# Writes internal/notices/THIRD_PARTY_NOTICES.txt: the license and notice
# texts of every third-party module linked into the gateway on any released
# platform, plus Go's own. The binary embeds the file (`notices` command) and
# GoReleaser adds it to every archive.
#
#   scripts/third-party-notices.sh          regenerate the file
#   scripts/third-party-notices.sh --check  fail if the committed file is stale
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${ROOT_DIR}/internal/notices/THIRD_PARTY_NOTICES.txt"
cd "${ROOT_DIR}"
# Go's own license text changes between releases, so take it from the toolchain
# go.mod names (the one CI and the release build with), not whatever is installed.
GOTOOLCHAIN="go$(GOTOOLCHAIN=local go list -m -f '{{.GoVersion}}')"
export GOTOOLCHAIN

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

go mod download
main_module="$(go list -m)"
# Linked modules differ per platform (golang.org/x/sys/windows, for one), so
# take the union over every GOOS/GOARCH in .goreleaser.yml.
for goos in linux darwin windows; do
  for goarch in amd64 arm64; do
    GOOS="${goos}" GOARCH="${goarch}" CGO_ENABLED=0 \
      go list -e -deps -f '{{with .Module}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}' .
  done
done | awk -F'\t' -v main="${main_module}" 'NF == 3 && $1 != main' | sort -u > "${work}/modules.tsv"

license_files() { # <dir>
  find "$1" -maxdepth 1 -type f | grep -iE '/(licen[cs]e|copying|notice|patents)([.-][^/]*)?$' | LC_ALL=C sort
}
: > "${work}/texts.tsv"
add_texts() { # <dir> <label>
  local file hash
  while read -r file; do
    hash="$(cksum < "${file}" | tr ' ' '-')"
    [ -e "${work}/${hash}" ] || cat "${file}" > "${work}/${hash}"
    printf '%s\t%s\n' "${hash}" "$2" >> "${work}/texts.tsv"
  done < <(license_files "$1")
}

add_texts "$(go env GOROOT)" "Go standard library and runtime"
while IFS=$'\t' read -r path version dir; do
  if [ -z "$(license_files "${dir}")" ]; then
    echo "${path}@${version} has no license file in ${dir}" >&2
    exit 1
  fi
  add_texts "${dir}" "${path}@${version}"
done < "${work}/modules.tsv"

generated="${work}/THIRD_PARTY_NOTICES.txt"
{
  echo "Third-party software notices"
  echo "============================"
  echo
  echo "Third-party modules linked into agentkeeper-mcp-gateway, with their license and notice texts."
  echo "Generated by scripts/third-party-notices.sh; do not edit."
  echo
  echo "Components"
  echo "----------"
  awk -F'\t' '{ printf "%s %s\n", $1, $2 }' "${work}/modules.tsv"
  # One section per distinct text, ordered by the first module it applies to
  cut -f1 "${work}/texts.tsv" | LC_ALL=C sort -u | while read -r hash; do
    printf '%s\t%s\n' "$(awk -F'\t' -v h="${hash}" '$1 == h { print $2 }' "${work}/texts.tsv" | LC_ALL=C sort | head -n1)" "${hash}"
  done | LC_ALL=C sort | while IFS=$'\t' read -r _ hash; do
    echo
    echo "--------------------------------------------------------------------------------"
    echo "Applies to:"
    awk -F'\t' -v h="${hash}" '$1 == h { print "  " $2 }' "${work}/texts.tsv" | LC_ALL=C sort -u
    echo
    cat "${work}/${hash}"
  done
} > "${generated}"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "${generated}" "${OUT}"; then
    diff -u "${OUT}" "${generated}" | head -40 >&2 || true
    echo "${OUT#"${ROOT_DIR}/"} is stale; run scripts/third-party-notices.sh and commit the result." >&2
    exit 1
  fi
  echo "${OUT#"${ROOT_DIR}/"} is up to date."
else
  mkdir -p "$(dirname "${OUT}")"
  cp "${generated}" "${OUT}"
  echo "Wrote ${OUT#"${ROOT_DIR}/"}: $(wc -l < "${work}/modules.tsv" | tr -d ' ') modules."
fi
